const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const elements=new Map();
const element=id=>elements.get(id)||elements.set(id,{textContent:'',innerHTML:'',classList:{toggle(){}},querySelector(){return null}}).get(id);
